/** 按 URL 路径取定制步骤；无定制时回退通用文案 */
export function stepsFor(pathname: string): string[] {
  const exact = USAGE_GUIDES[pathname];
  if (exact) return exact;
  const withSlash = pathname.endsWith("/") ? pathname : pathname + "/";
  return USAGE_GUIDES[withSlash] ?? GENERIC_STEPS;
}
