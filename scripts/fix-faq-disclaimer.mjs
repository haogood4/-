let faqPatched = 0;
let discPatched = 0;
const errors = [];

for (const [page, items] of Object.entries(FAQ)) {
  const path = `src/pages/${page}.astro`;
  let s;
  try {
    s = readFileSync(path, "utf8");
  } catch {
    errors.push(`${page}: 文件不存在`);
    continue;
  }
  const m = s.match(/const faqItems = \[([\s\S]*?)\];/);
  if (!m) {
    errors.push(`${page}: 未找到 faqItems 数组`);
    continue;
  }
  const additions = items
    .map(([q, a]) => `{ q: ${JSON.stringify(q)}, a: ${JSON.stringify(a)} }`)
    .join(", ");
  const body = m[1].trim();
  const sep = body.length > 0 && !body.endsWith(",") ? ", " : "";
  const replacement = `const faqItems = [${m[1]}${sep}${additions}];`;
  s = s.replace(m[0], replacement);
  if (!DRY) writeFileSync(path, s);
  faqPatched++;
}

for (const [page, html] of Object.entries(DISCLAIMER)) {
  const path = `src/pages/${page}.astro`;
  let s = readFileSync(path, "utf8");
  if (/仅供参考/.test(s)) {
    errors.push(`${page}: 已有免责声明，跳过`);
    continue;
  }
  const lead = s.match(/<p class="lead">[\s\S]*?<\/p>\n/);
  if (!lead) {
    errors.push(`${page}: 未找到 lead 段落`);
    continue;
  }
  s = s.replace(lead[0], `${lead[0]}    ${html}\n`);
  if (!DRY) writeFileSync(path, s);
  discPatched++;
}

console.log(`FAQ 补足 ${faqPatched} 页；disclaimer 补充 ${discPatched} 页`);
if (errors.length) console.log("问题：\n" + errors.join("\n"));
